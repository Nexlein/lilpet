// Generates the C files that come from the JS side:
// - engine/tests/js_vectors.h: values computed by the JS prototype (prototype/eyes.js) that the C engine must reproduce
//   (engine/tests/test_parity.c)
// - engine/src/emotions_table.h: the emotions and reactions of eyes/emotions.json, as C tables
// Run it after changing eyes.js, scenes.json, looks.json or emotions.json.
// Usage: node scripts/gen-engine-vectors.mjs [--check]   (--check: fail if a committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { BASE, EMOTIONS, Eyes, REACTIONS, createRng, makeLook } from '../prototype/eyes.js';

const VECTORS = 'engine/tests/js_vectors.h';
const TABLES = 'engine/src/emotions_table.h';
// Time step of the simulations: a power of two, so time sums are exact in both float (C) and double (JS)
const DT = 1 / 64;

const emotionEnum = (name) => `LP_EMOTION_${name.toUpperCase()}`;
const eventEnum = (name) => `LP_EVENT_${name.toUpperCase()}`;
const particleEnum = (type) => `LP_PARTICLE_${(type ?? 'none').toUpperCase()}`;
const phaseEnum = (phase) => `LP_BLINK_${(phase ?? 'none').toUpperCase()}`;
const num = (v) => {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    const s = Object.is(v, -0) ? '0' : String(+v.toPrecision(9));
    return /[.e]/.test(s) ? `${s}f` : `${s}.0f`;
};

// State snapshot shared by simulations and scenes (struct lpv_state in the header)
function snapshot(eyes, time) {
    const { gaze, head, cur, blinkState, particles } = eyes;
    return [
        num(time),
        num(gaze.x),
        num(gaze.y),
        num(gaze.tx),
        num(gaze.ty),
        num(gaze.vx),
        num(gaze.vy),
        num(head.yaw),
        num(head.pitch),
        num(head.roll),
        num(cur.tl),
        num(cur.bl),
        num(cur.gy),
        num(cur.ps),
        phaseEnum(blinkState.phase),
        String(particles.length),
        num(particles.reduce((s, p) => s + p.x, 0)),
        num(particles.reduce((s, p) => s + p.y, 0)),
        emotionEnum(eyes.emotion)
    ];
}
const row = (fields) => `    {${fields.join(', ')}},`;

const lines = [];
const out = (...l) => lines.push(...l);

out(
    '/* Generated by scripts/gen-engine-vectors.mjs from prototype/eyes.js: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_JS_VECTORS_H',
    '#define LILPET_JS_VECTORS_H',
    '',
    '#include "lilpet/lilpet.h"',
    '',
    `#define LPV_DT ${num(DT)}`,
    ''
);

// --- Random numbers: k such that value = k / 2^24 (exact in both languages) -------------------------
const RNG_SEEDS = [1, 42, 0xdeadbeef];
const RNG_COUNT = 16;
out(`static const uint32_t LPV_RNG_SEEDS[${RNG_SEEDS.length}] = {${RNG_SEEDS.map((s) => `${s}u`).join(', ')}};`);
out(`static const uint32_t LPV_RNG_K[${RNG_SEEDS.length}][${RNG_COUNT}] = {`);
for (const seed of RNG_SEEDS) {
    const r = createRng(seed);
    out(`    {${Array.from({ length: RNG_COUNT }, () => `${r() * 16777216}u`).join(', ')}},`);
}
out('};', '');

// --- Names, in the order of lp_emotion and lp_event, the enums written by hand -------------------------
const cNames = (names) => names.map((name) => `"${name}"`).join(', ');
out(
    `static const char *const LPV_EMOTION_NAMES[${Object.keys(EMOTIONS).length}] = {${cNames(Object.keys(EMOTIONS))}};`
);
out(
    `static const char *const LPV_EVENT_NAMES[${Object.keys(REACTIONS).length}] = {${cNames(Object.keys(REACTIONS))}};`
);
out('');

// --- Blink poses ---------------------------------------------------------------------------------
const BLINKS = [
    ['anticip', 0.03],
    ['anticip', 0.06],
    ['close', 0.04],
    ['close', 0.1],
    ['closed', 0.05],
    ['open', 0.05],
    ['open', 0.2],
    [null, 0]
];
const poser = new Eyes(1);
out('typedef struct { lp_blink_phase phase; float t, open; lp_blink_pose pose; } lpv_blink;');
out(`static const lpv_blink LPV_BLINKS[${BLINKS.length}] = {`);
for (const [phase, t] of BLINKS) {
    Object.assign(poser.blinkState, { phase, t, open: 0.2 });
    const p = poser.blinkPose();
    out(`    {${phaseEnum(phase)}, ${num(t)}, ${num(0.2)}, {${num(p.lid)}, ${num(p.sx)}, ${num(p.sy)}, ${p.closed}}},`);
}
out('};', '');

// --- Eye poses on the 3D head ----------------------------------------------------------------------
const HEADS = [
    [0, 0, 0],
    [0.33, 0, -0.13],
    [-0.3, -0.2, 0.25],
    [0.1, 0.4, 0]
];
out('typedef struct { float yaw, pitch, roll; int side; lp_eye_pose pose; } lpv_eye;');
out(`static const lpv_eye LPV_EYES[${HEADS.length * 2}] = {`);
for (const [yaw, pitch, roll] of HEADS) {
    Object.assign(poser.head, { yaw, pitch, roll });
    for (const side of [-1, 1]) {
        const p = poser.eyePose(side);
        out(
            `    {${num(yaw)}, ${num(pitch)}, ${num(roll)}, ${side}, {${[p.x, p.y, p.persp, p.fx, p.fy].map(num).join(', ')}}},`
        );
    }
}
out('};', '');

// --- Simulations: from a seed, run update() and take snapshots ----------------------------------------
out(
    'typedef struct {',
    '    float time, gaze_x, gaze_y, gaze_tx, gaze_ty, gaze_vx, gaze_vy, yaw, pitch, roll, tl, bl, gy, ps;',
    '    lp_blink_phase blink;',
    '    int particles;',
    '    float particles_x, particles_y; /* sums of the particle positions */',
    '    lp_emotion emotion;',
    '} lpv_state;',
    ''
);
const SCENARIOS = [
    { name: 'idle', seed: 7, steps: 640, every: 32 },
    { name: 'love', seed: 11, emotion: 'love', steps: 384, every: 32 },
    { name: 'petting', seed: 3, react: 'tap', steps: 256, every: 16 },
    { name: 'dizzy', seed: 23, react: 'shake', steps: 384, every: 16 },
    { name: 'shaken', seed: 29, shaking: true, steps: 256, every: 32 },
    { name: 'tracking', seed: 5, pointer: [0.5, -0.3], steps: 256, every: 32 },
    // Gravity in the screen plane: object turned about 70 degrees, then about 150 (back toward upright)
    { name: 'turned', seed: 13, gravity: [0.9375, 0.34375], steps: 256, every: 32 },
    { name: 'upside-down', seed: 17, gravity: [0.5, -0.875], steps: 256, every: 32 },
    // Object turning clockwise at 2 radians per second, standing up: 2.5 turns, the face stays level
    { name: 'turning', seed: 19, spin: 2, steps: 512, every: 32 },
    { name: 'sleepy', seed: 9, emotion: 'sleepy', steps: 640, every: 64 }
];
const states = [];
const scenarioRows = [];
for (const s of SCENARIOS) {
    const eyes = new Eyes(s.seed);
    if (s.emotion) eyes.setEmotion(s.emotion);
    if (s.react) eyes.react(s.react);
    eyes.shaking = Boolean(s.shaking);
    if (s.pointer) eyes.setPointer({ x: s.pointer[0], y: s.pointer[1] });
    if (s.gravity) eyes.setGravity({ x: s.gravity[0], y: s.gravity[1] });
    const first = states.length;
    let t = 0;
    for (let i = 1; i <= s.steps; i++) {
        t += DT;
        if (s.spin) eyes.setGravity({ x: Math.sin(s.spin * t), y: Math.cos(s.spin * t) });
        eyes.update(DT, t);
        if (i % s.every === 0) states.push(row(snapshot(eyes, t)));
    }
    scenarioRows.push(
        `    {"${s.name}", ${s.seed}u, ${emotionEnum(s.emotion ?? 'neutral')}, ${s.react ? eventEnum(s.react) : -1}, ` +
            `${num(s.pointer?.[0] ?? 0)}, ${num(s.pointer?.[1] ?? 0)}, ` +
            `${num(s.gravity?.[0] ?? 0)}, ${num(s.gravity?.[1] ?? 0)}, ${num(s.spin ?? 0)}, ` +
            `${s.steps}, ${s.every}, ${first}, ${states.length - first}, ${Boolean(s.pointer)}, ${Boolean(s.gravity)}, ` +
            `${Boolean(s.shaking)}},`
    );
}
out(`static const lpv_state LPV_STATES[${states.length}] = {`, ...states, '};', '');
out(
    'typedef struct {',
    '    const char *name;',
    '    uint32_t seed;',
    '    lp_emotion emotion;',
    '    int react; /* lp_event at the start, or -1 */',
    '    float pointer_x, pointer_y;',
    '    float gravity_x, gravity_y;',
    '    float spin; /* radians per second: gravity turning in the screen plane, from upright */',
    '    int steps, every, first_state, state_count;',
    '    bool pointer, gravity, shaking;',
    '} lpv_scenario;',
    `static const lpv_scenario LPV_SCENARIOS[${SCENARIOS.length}] = {`,
    ...scenarioRows,
    '};',
    ''
);

// --- Reference scenes: the looks they wear, and the state right after setScene ---------------------------
const swatches = new Map(JSON.parse(readFileSync('eyes/looks.json', 'utf8')).swatches.map((s) => [s.id, s]));
const scenes = JSON.parse(readFileSync('prototype/scenes.json', 'utf8')).scenes;
const lookOf = (scene) => makeLook(swatches.get(scene.swatch), scene.pupil);
const lookKeys = [...new Set(scenes.map((s) => `${s.swatch} ${s.pupil}`))];
const hex = (c) => `0x${c.slice(1).toUpperCase()}u`;
out(`static const lp_look LPV_LOOKS[${lookKeys.length}] = {`);
for (const key of lookKeys) {
    const scene = scenes.find((s) => `${s.swatch} ${s.pupil}` === key);
    const l = lookOf(scene);
    out(
        `    {${hex(l.sclera)}, LP_PUPIL_${l.pupil.toUpperCase()}, {${hex(l.pupilColor[0])}, ${hex(l.pupilColor[1])}}}, /* ${key} */`
    );
}
out('};', '');
out('typedef struct { const char *id; int look; lp_scene scene; lpv_state expected; } lpv_scene;');
out(`static const lpv_scene LPV_SCENES[${scenes.length}] = {`);
for (const scene of scenes) {
    const eyes = new Eyes(1);
    eyes.setScene(scene, lookOf(scene));
    const sc = [
        emotionEnum(scene.emotion ?? 'neutral'),
        phaseEnum(scene.blink?.phase),
        num(scene.blink?.t ?? 0),
        num(scene.head?.yaw ?? 0),
        num(scene.head?.pitch ?? 0),
        num(scene.head?.roll ?? 0),
        num(scene.gaze?.x ?? 0),
        num(scene.gaze?.y ?? 0),
        String(Boolean(scene.particles)),
        `${scene.particles?.seed ?? 0}u`,
        num(scene.particles?.time ?? 0)
    ];
    const lookIndex = lookKeys.indexOf(`${scene.swatch} ${scene.pupil}`);
    out(`    {"${scene.id}", ${lookIndex}, {${sc.join(', ')}}, {${snapshot(eyes, 0).join(', ')}}},`);
}
out('};', '', '#endif /* LILPET_JS_VECTORS_H */', '');

// --- Emotions and reactions as C tables --------------------------------------------------------------
// Each row names its enumerator, so that a row without one does not compile; the count is checked too, so that an
// enumerator without a row does not compile either
const EXPR = Object.keys(BASE); // the fields of lp_expression: a new one breaks the C build until ported
const note = (entry) => (entry.note ? ` /* ${entry.note} */` : '');
const countCheck = (count, enumerator, name) =>
    `_Static_assert(${enumerator} == ${count}, "${name} in lilpet.h and in eyes/emotions.json differ");`;
const tables = [
    '/* Generated by scripts/gen-engine-vectors.mjs from eyes/emotions.json: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_EMOTIONS_TABLE_H',
    '#define LILPET_EMOTIONS_TABLE_H',
    '',
    '#include "lilpet/lilpet.h"',
    '',
    countCheck(Object.keys(EMOTIONS).length, 'LP_EMOTION_COUNT', 'lp_emotion'),
    'static const lp_emotion_def EMOTIONS[LP_EMOTION_COUNT] = {'
];
for (const [name, e] of Object.entries(EMOTIONS))
    tables.push(
        `    [${emotionEnum(name)}] = {${note(e)}`,
        `        .name = "${name}",`,
        `        .expr = {${EXPR.map((k) => `.${k} = ${num(e[k])}`).join(', ')}},`,
        `        .emit = ${particleEnum(e.emit?.type)},`,
        `        .emit_rate = ${num(e.emit?.rate ?? 0)},`,
        '    },'
    );
tables.push(
    '};',
    '',
    countCheck(Object.keys(REACTIONS).length, 'LP_EVENT_COUNT', 'lp_event'),
    'static const lp_reaction REACTIONS[LP_EVENT_COUNT] = {'
);
for (const [name, r] of Object.entries(REACTIONS))
    tables.push(
        `    [${eventEnum(name)}] = {.name = "${name}", .emotion = ${emotionEnum(r.emotion)}, ` +
            `.duration = ${num(r.duration)}, .sparkles = ${r.sparkles}},${note(r)}`
    );
tables.push('};', '', '#endif /* LILPET_EMOTIONS_TABLE_H */', '');

function current(path) {
    try {
        return readFileSync(path, 'utf8');
    } catch {
        return ''; // missing file: reported as out of date
    }
}

const files = [
    [VECTORS, lines.join('\n')],
    [TABLES, tables.join('\n')]
];
if (process.argv.includes('--check')) {
    const stale = files.filter(([path, text]) => current(path) !== text).map(([path]) => path);
    if (stale.length) {
        console.error(`${stale.join(', ')}: out of date, run node scripts/gen-engine-vectors.mjs`);
        process.exit(1);
    }
    console.log(`${files.map(([path]) => path).join(', ')}: up to date`);
} else {
    for (const [path, text] of files) writeFileSync(path, text);
    console.log(`${VECTORS}: ${states.length} simulation states, ${scenes.length} scenes; ${TABLES} written`);
}
