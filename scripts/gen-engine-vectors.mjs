// Generates engine/tests/js_vectors.h: values computed by the JS prototype (prototype/eyes.js) that the C engine
// must reproduce (engine/tests/test_parity.c). Run it after changing eyes.js, scenes.json or looks.json.
// Usage: node scripts/gen-engine-vectors.mjs [--check]   (--check: fail if the committed file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { EMOTIONS, Eyes, createRng, makeLook } from '../prototype/eyes.js';

const OUT = 'engine/tests/js_vectors.h';
// Time step of the simulations: a power of two, so time sums are exact in both float (C) and double (JS)
const DT = 1 / 64;

const EMOTION_NAMES = Object.keys(EMOTIONS);
const emotionEnum = (name) => `LP_EMOTION_${name.toUpperCase()}`;
const particleEnum = (type) => `LP_PARTICLE_${(type ?? 'none').toUpperCase()}`;
const phaseEnum = (phase) => `LP_BLINK_${(phase ?? 'none').toUpperCase()}`;
const num = (v) => {
    if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
    const s = Object.is(v, -0) ? '0' : String(+v.toPrecision(9));
    return /[.e]/.test(s) ? `${s}f` : `${s}.0f`;
};

// State snapshot shared by simulations and scenes (struct lpv_state in the header)
function snapshot(eyes, time) {
    const { gaze, head, cur, blinkState, particles } = eyes;
    return [
        num(time),
        num(gaze.x),
        num(gaze.y),
        num(gaze.tx),
        num(gaze.ty),
        num(head.yaw),
        num(head.pitch),
        num(head.roll),
        num(cur.tl),
        num(cur.bl),
        num(cur.gy),
        num(cur.ps),
        phaseEnum(blinkState.phase),
        String(particles.length),
        num(particles.reduce((s, p) => s + p.x, 0)),
        num(particles.reduce((s, p) => s + p.y, 0)),
        emotionEnum(eyes.emotion)
    ];
}
const row = (fields) => `    {${fields.join(', ')}},`;

const lines = [];
const out = (...l) => lines.push(...l);

out(
    '/* Generated by scripts/gen-engine-vectors.mjs from prototype/eyes.js: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_JS_VECTORS_H',
    '#define LILPET_JS_VECTORS_H',
    '',
    '#include "lilpet/lilpet.h"',
    '',
    `#define LPV_DT ${num(DT)}`,
    ''
);

// --- Random numbers: k such that value = k / 2^24 (exact in both languages) -------------------------
const RNG_SEEDS = [1, 42, 0xdeadbeef];
const RNG_COUNT = 16;
out(`static const uint32_t LPV_RNG_SEEDS[${RNG_SEEDS.length}] = {${RNG_SEEDS.map((s) => `${s}u`).join(', ')}};`);
out(`static const uint32_t LPV_RNG_K[${RNG_SEEDS.length}][${RNG_COUNT}] = {`);
for (const seed of RNG_SEEDS) {
    const r = createRng(seed);
    out(`    {${Array.from({ length: RNG_COUNT }, () => `${r() * 16777216}u`).join(', ')}},`);
}
out('};', '');

// --- Emotion table -------------------------------------------------------------------------------
const EXPR = ['tl', 'ts', 'bl', 'sq', 'cr', 'rot', 'hl', 'ps', 'es', 'gy'];
out(`static const lp_emotion_def LPV_EMOTIONS[${EMOTION_NAMES.length}] = {`);
for (const name of EMOTION_NAMES) {
    const e = EMOTIONS[name];
    out(
        `    {"${name}", {${EXPR.map((k) => num(e[k])).join(', ')}}, ${particleEnum(e.emit?.type)}, ${num(e.emit?.rate ?? 0)}},`
    );
}
out('};', '');

// --- Blink poses ---------------------------------------------------------------------------------
const BLINKS = [
    ['anticip', 0.03],
    ['anticip', 0.06],
    ['close', 0.04],
    ['close', 0.1],
    ['closed', 0.05],
    ['open', 0.05],
    ['open', 0.2],
    [null, 0]
];
const poser = new Eyes(null, { seed: 1 });
out('typedef struct { lp_blink_phase phase; float t, open; lp_blink_pose pose; } lpv_blink;');
out(`static const lpv_blink LPV_BLINKS[${BLINKS.length}] = {`);
for (const [phase, t] of BLINKS) {
    Object.assign(poser.blinkState, { phase, t, open: 0.2 });
    const p = poser.blinkPose();
    out(`    {${phaseEnum(phase)}, ${num(t)}, ${num(0.2)}, {${num(p.lid)}, ${num(p.sx)}, ${num(p.sy)}, ${p.closed}}},`);
}
out('};', '');

// --- Eye poses on the 3D head ----------------------------------------------------------------------
const HEADS = [
    [0, 0, 0],
    [0.33, 0, -0.13],
    [-0.3, -0.2, 0.25],
    [0.1, 0.4, 0]
];
out('typedef struct { float yaw, pitch, roll; int side; lp_eye_pose pose; } lpv_eye;');
out(`static const lpv_eye LPV_EYES[${HEADS.length * 2}] = {`);
for (const [yaw, pitch, roll] of HEADS) {
    Object.assign(poser.head, { yaw, pitch, roll });
    for (const side of [-1, 1]) {
        const p = poser.eyePose(side);
        out(
            `    {${num(yaw)}, ${num(pitch)}, ${num(roll)}, ${side}, {${[p.x, p.y, p.persp, p.fx, p.fy].map(num).join(', ')}}},`
        );
    }
}
out('};', '');

// --- Simulations: from a seed, run update() and take snapshots ----------------------------------------
out(
    'typedef struct {',
    '    float time, gaze_x, gaze_y, gaze_tx, gaze_ty, yaw, pitch, roll, tl, bl, gy, ps;',
    '    lp_blink_phase blink;',
    '    int particles;',
    '    float particles_x, particles_y; /* sums of the particle positions */',
    '    lp_emotion emotion;',
    '} lpv_state;',
    ''
);
const SCENARIOS = [
    { name: 'idle', seed: 7, steps: 640, every: 32 },
    { name: 'love', seed: 11, emotion: 'love', steps: 384, every: 32 },
    { name: 'petting', seed: 3, emotion: 'happy', duration: 1, sparkles: 4, steps: 256, every: 16 },
    { name: 'tracking', seed: 5, pointer: [0.5, -0.3], steps: 256, every: 32 },
    { name: 'sleepy', seed: 9, emotion: 'sleepy', steps: 640, every: 64 }
];
const states = [];
const scenarioRows = [];
for (const s of SCENARIOS) {
    const eyes = new Eyes(null, { seed: s.seed });
    if (s.emotion) eyes.setEmotion(s.emotion, s.duration ?? 0);
    for (let i = 0; i < (s.sparkles ?? 0); i++) eyes.spawn('sparkle');
    if (s.pointer) eyes.mouse = { x: s.pointer[0], y: s.pointer[1] };
    const first = states.length;
    let t = 0;
    for (let i = 1; i <= s.steps; i++) {
        t += DT;
        eyes.update(DT, t);
        if (i % s.every === 0) states.push(row(snapshot(eyes, t)));
    }
    scenarioRows.push(
        `    {"${s.name}", ${s.seed}u, ${emotionEnum(s.emotion ?? 'neutral')}, ${num(s.duration ?? 0)}, ${s.sparkles ?? 0}, ` +
            `${Boolean(s.pointer)}, ${num(s.pointer?.[0] ?? 0)}, ${num(s.pointer?.[1] ?? 0)}, ${s.steps}, ${s.every}, ${first}, ${states.length - first}},`
    );
}
out(`static const lpv_state LPV_STATES[${states.length}] = {`, ...states, '};', '');
out(
    'typedef struct {',
    '    const char *name;',
    '    uint32_t seed;',
    '    lp_emotion emotion;',
    '    float emotion_duration;',
    '    int sparkles;',
    '    bool pointer;',
    '    float pointer_x, pointer_y;',
    '    int steps, every, first_state, state_count;',
    '} lpv_scenario;',
    `static const lpv_scenario LPV_SCENARIOS[${SCENARIOS.length}] = {`,
    ...scenarioRows,
    '};',
    ''
);

// --- Reference scenes: the looks they wear, and the state right after setScene ---------------------------
const swatches = new Map(JSON.parse(readFileSync('eyes/looks.json', 'utf8')).swatches.map((s) => [s.id, s]));
const scenes = JSON.parse(readFileSync('prototype/scenes.json', 'utf8')).scenes;
const lookOf = (scene) => makeLook(swatches.get(scene.swatch), scene.pupil);
const lookKeys = [...new Set(scenes.map((s) => `${s.swatch} ${s.pupil}`))];
const hex = (c) => `0x${c.slice(1).toUpperCase()}u`;
out(`static const lp_look LPV_LOOKS[${lookKeys.length}] = {`);
for (const key of lookKeys) {
    const scene = scenes.find((s) => `${s.swatch} ${s.pupil}` === key);
    const l = lookOf(scene);
    out(
        `    {${hex(l.sclera)}, LP_PUPIL_${l.pupil.toUpperCase()}, {${hex(l.pupilColor[0])}, ${hex(l.pupilColor[1])}}}, /* ${key} */`
    );
}
out('};', '');
out('typedef struct { const char *id; int look; lp_scene scene; lpv_state expected; } lpv_scene;');
out(`static const lpv_scene LPV_SCENES[${scenes.length}] = {`);
for (const scene of scenes) {
    const eyes = new Eyes(null, { seed: 1 });
    eyes.setScene(scene, lookOf(scene));
    const sc = [
        emotionEnum(scene.emotion ?? 'neutral'),
        phaseEnum(scene.blink?.phase),
        num(scene.blink?.t ?? 0),
        num(scene.head?.yaw ?? 0),
        num(scene.head?.pitch ?? 0),
        num(scene.head?.roll ?? 0),
        num(scene.gaze?.x ?? 0),
        num(scene.gaze?.y ?? 0),
        String(Boolean(scene.particles)),
        `${scene.particles?.seed ?? 0}u`,
        num(scene.particles?.time ?? 0)
    ];
    const lookIndex = lookKeys.indexOf(`${scene.swatch} ${scene.pupil}`);
    out(`    {"${scene.id}", ${lookIndex}, {${sc.join(', ')}}, {${snapshot(eyes, 0).join(', ')}}},`);
}
out('};', '', '#endif /* LILPET_JS_VECTORS_H */', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = readFileSync(OUT, 'utf8');
    } catch {
        // missing file: reported below
    }
    if (current !== text) {
        console.error(`${OUT} is out of date: run node scripts/gen-engine-vectors.mjs`);
        process.exit(1);
    }
    console.log(`${OUT} is up to date`);
} else {
    writeFileSync(OUT, text);
    console.log(`${OUT}: ${states.length} simulation states, ${scenes.length} scenes`);
}
