// Generates engine/src/looks_table.h: what eyes/looks.json says about every look, as C tables: the default look, the
// eye shape and the pupil shapes. The swatches stay in the JSON: the PC app sends a look's colors, the engine never
// needs the catalogue. Run it after changing looks.json (npm run tables runs every generator).
// Usage: node scripts/gen-looks-table.mjs [--check]   (--check: fail if the committed file is out of date)
import { LOOKS, LOOKS_TABLE, readJson } from './data.mjs';
import { num, writeGenerated } from './gen-common.mjs';

const data = readJson(LOOKS);

const pupilEnum = (type) => `LP_PUPIL_${type.toUpperCase()}`;
const color = (hex) => `0x${hex.slice(1).toUpperCase()}u`;
const swatch = data.swatches.find((s) => s.id === data.default.swatch);
const pupils = Object.entries(data.pupils);

const lines = [
    '/* Generated by scripts/gen-looks-table.mjs from eyes/looks.json: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_LOOKS_TABLE_H',
    '#define LILPET_LOOKS_TABLE_H',
    '',
    '#include "internal.h"',
    '#include "lilpet/lilpet.h"',
    '',
    `static const lp_look DEFAULT_LOOK = {.sclera = ${color(swatch.sclera)}, .pupil = ${pupilEnum(data.default.pupil)}, ` +
        `.pupil_color = {${swatch.pupilColor.map(color).join(', ')}}}; /* ${swatch.id} */`,
    `static const lp_shape DEFAULT_SHAPE = {.rx = ${num(data.eye.rx)}, .ry = ${num(data.eye.ry)}, ` +
        `.gap = ${num(data.eye.gap)}, .tilt = ${num(data.eye.tilt)}};`,
    '',
    `_Static_assert(LP_PUPIL_COUNT == ${pupils.length}, "lp_pupil in lilpet.h and the pupils of eyes/looks.json differ");`,
    `#define LP_PUPIL_LIST "${pupils.map(([type]) => type).join('|')}" /* for the messages that list them */`,
    'static const lp_pupils PUPILS = {',
    `    .lean = ${num(data.pupilLean)},`,
    '    .types = {'
];
for (const [type, p] of pupils) {
    const [rx, ry] =
        p.r === undefined ? [p.rx, p.ry] : [p.r, p.r]; /* a disc: the renderer takes both from the eye's rx */
    lines.push(
        `        [${pupilEnum(type)}] = {.name = "${type}", .rx = ${num(rx)}, .ry = ${num(ry)}, .x = ${num(p.x)}, ` +
            `.y = ${num(p.y)}},`
    );
}
// The longest look text: three colors and their spaces, the longest pupil name, the NUL
const longest = Math.max(...pupils.map(([type]) => type.length));
lines.push(
    '    },',
    '};',
    `_Static_assert(3 * 7 + ${longest} + 1 <= LP_LOOK_TEXT_SIZE, "a pupil name of eyes/looks.json is too long for LP_LOOK_TEXT_SIZE");`,
    '',
    '#endif /* LILPET_LOOKS_TABLE_H */',
    ''
);

writeGenerated(
    LOOKS_TABLE,
    lines.join('\n'),
    `default ${swatch.id} ${data.default.pupil}, ${pupils.length} pupil types`
);
