// Generates engine/tests/scenes_table.h: the reference scenes of engine/tests/scenes.json and the looks they wear (from
// eyes/looks.json), as C tables for the engine's tests and the renderer benchmark (engine/tools/bench.c). Apart from
// gen-emotions-table.mjs, so that a fault in the scenes never stops the tables that the engine builds from.
// Usage: node scripts/gen-scenes-table.mjs [--check]   (--check: fail if the committed file is out of date)
import { SCENES, SCENES_TABLE, lookOf, readJson, swatchesById } from './data.mjs';
import { emotionEnum, num, writeGenerated } from './gen-common.mjs';

const swatches = swatchesById();
const scenes = readJson(SCENES).scenes;
// The looks the scenes wear, each once, in the order they first appear: the first scene that wears each one
const lookKey = (scene) => `${scene.swatch} ${scene.pupil}`;
const firstWearers = scenes.filter((scene, i) => scenes.findIndex((s) => lookKey(s) === lookKey(scene)) === i);
const lookIndex = new Map(firstWearers.map((scene, i) => [lookKey(scene), i]));
const hex = (c) => `0x${c.slice(1).toUpperCase()}u`;
const phaseEnum = (phase) => `LP_BLINK_${(phase ?? 'none').toUpperCase()}`;

const lines = [
    '/* Generated by scripts/gen-scenes-table.mjs from engine/tests/scenes.json and eyes/looks.json: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_SCENES_TABLE_H',
    '#define LILPET_SCENES_TABLE_H',
    '',
    '#include "lilpet/lilpet.h"',
    '',
    `static const lp_look SCENE_LOOKS[${firstWearers.length}] = {`
];
for (const scene of firstWearers) {
    const look = lookOf(swatches, scene);
    lines.push(
        `    {${hex(look.sclera)}, LP_PUPIL_${look.pupil.toUpperCase()}, {${hex(look.pupilColor[0])}, ${hex(look.pupilColor[1])}}}, /* ${lookKey(scene)} */`
    );
}
lines.push(
    '};',
    '',
    'typedef struct { const char *id; const lp_look *look; lp_scene scene; } reference_scene; /* look: in SCENE_LOOKS */',
    `static const reference_scene SCENES[${scenes.length}] = {`
);
for (const scene of scenes) {
    // By name: lp_scene holds several floats in a row, which a field moved in lilpet.h would silently swap
    const fields = Object.entries({
        emotion: emotionEnum(scene.emotion ?? 'neutral'),
        blink_phase: phaseEnum(scene.blink?.phase),
        blink_t: num(scene.blink?.t ?? 0),
        yaw: num(scene.head?.yaw ?? 0),
        pitch: num(scene.head?.pitch ?? 0),
        roll: num(scene.head?.roll ?? 0),
        gaze_x: num(scene.gaze?.x ?? 0),
        gaze_y: num(scene.gaze?.y ?? 0),
        has_particles: String(Boolean(scene.particles)),
        particle_seed: `${scene.particles?.seed ?? 0}u`,
        particle_time: num(scene.particles?.time ?? 0)
    }).map(([field, value]) => `.${field} = ${value}`);
    lines.push(`    {"${scene.id}", &SCENE_LOOKS[${lookIndex.get(lookKey(scene))}], {${fields.join(', ')}}},`);
}
lines.push('};', '', '#endif /* LILPET_SCENES_TABLE_H */', '');

writeGenerated(SCENES_TABLE, lines.join('\n'), `${scenes.length} scenes wearing ${firstWearers.length} looks`);
