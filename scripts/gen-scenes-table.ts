// Generates engine/tests/scenes_table.h: the reference scenes of engine/tests/scenes.json, as the fields of lp_scene
// that sceneFields (engine/wasm/engine.ts) reads them into, and the looks they wear (from eyes/looks.json), as C tables
// for the engine's tests and the renderer benchmark (engine/tools/bench.c). Apart from
// gen-emotions-table.ts, so that a fault in the scenes never stops the tables that the engine builds from.
// Usage: node scripts/gen-scenes-table.ts [--check]   (--check: fail if the committed file is out of date)
import { sceneFields } from '../engine/wasm/engine.ts';
import { SCENES_TABLE, lookOf, readScenes, swatchesById, type ReferenceScene } from './data.ts';
import { emotionEnum, hexColor, num, pupilEnum, writeGenerated } from './gen-common.ts';

const swatches = swatchesById();
const scenes = readScenes().scenes;
// The looks the scenes wear, each once, in the order they first appear: the first scene that wears each one
const lookKey = (scene: ReferenceScene) => `${scene.swatch} ${scene.pupil}`;
const firstWearers = scenes.filter((scene, i) => scenes.findIndex((s) => lookKey(s) === lookKey(scene)) === i);
const lookIndex = new Map(firstWearers.map((scene, i) => [lookKey(scene), i]));
// How each field of sceneFields is written in C; the others are floats (a parameter of type never takes any converter)
const C_VALUES: Record<string, (value: never) => string> = {
    emotion: emotionEnum,
    blink_phase: (phase: string | null) => `LP_BLINK_${(phase ?? 'none').toUpperCase()}`,
    has_particles: String,
    particle_seed: (seed: number) => `${seed}u`
};

const lines = [
    '/* Generated by scripts/gen-scenes-table.ts from engine/tests/scenes.json, eyes/looks.json and the scene fields of',
    '   engine/wasm/engine.ts: do not edit. */',
    '/* clang-format off */',
    '#ifndef LILPET_SCENES_TABLE_H',
    '#define LILPET_SCENES_TABLE_H',
    '',
    '#include "lilpet/lilpet.h"',
    '',
    `static const lp_look SCENE_LOOKS[${firstWearers.length}] = {`
];
for (const scene of firstWearers) {
    const look = lookOf(swatches, scene);
    lines.push(
        `    {${hexColor(look.sclera)}, ${pupilEnum(look.pupil)}, {${hexColor(look.pupilColor[0])}, ${hexColor(look.pupilColor[1])}}}, /* ${lookKey(scene)} */`
    );
}
lines.push(
    '};',
    '',
    'typedef struct { const char *id; const lp_look *look; lp_scene scene; } reference_scene; /* look: in SCENE_LOOKS */',
    `static const reference_scene SCENES[${scenes.length}] = {`
);
for (const scene of scenes) {
    // By name: lp_scene holds several floats in a row, which a field moved in lilpet.h would silently swap
    const fields = Object.entries(sceneFields(scene)).map(
        ([field, value]) => `.${field} = ${(C_VALUES[field] ?? num)(value as never)}`
    );
    lines.push(`    {"${scene.id}", &SCENE_LOOKS[${lookIndex.get(lookKey(scene))}], {${fields.join(', ')}}},`);
}
lines.push('};', '', '#endif /* LILPET_SCENES_TABLE_H */', '');

writeGenerated(SCENES_TABLE, lines.join('\n'), `${scenes.length} scenes wearing ${firstWearers.length} looks`);
